#!/usr/bin/env python3
"""Build the single-page static site using only Python's standard library."""
from pathlib import Path
import hashlib
import html
import json
import re

ROOT = Path(__file__).resolve().parents[1]
CONTENT = ROOT / "content"


def build():
    settings = json.loads((CONTENT / "site.json").read_text())
    source = (ROOT / "templates" / "index.html").read_text()

    def include(match):
        path = (CONTENT / match.group(1)).resolve()
        if CONTENT.resolve() not in path.parents:
            raise ValueError(f"Content path outside content/: {path}")
        return path.read_text().rstrip()

    source = re.sub(r"\{\{include:([^}]+)\}\}", include, source)
    for key in ("title", "description"):
        source = source.replace("{{" + key + "}}", html.escape(settings["index"][key], quote=True))
    for kind in ("css", "js"):
        asset = ROOT / "static" / kind / f"index.{kind}"
        version = hashlib.sha256(asset.read_bytes()).hexdigest()[:12]
        source = source.replace("{{" + kind + "_version}}", version)
    source = "<!-- Generated by scripts/build.py. Edit content/ and templates/, then rebuild. -->\n" + source
    (ROOT / "index.html").write_text(source)
    print("Built index.html")


if __name__ == "__main__":
    build()
